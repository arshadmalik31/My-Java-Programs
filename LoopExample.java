class LoopExample 
{
	public static void main(String[] args) 
{
	char i='A';
	for(i='A';i<='Z';i++)
	{
		
		System.out.print(i+ " ");
		
	}
	System.out.println();

	char c='a';
	for(c='a';c<='z';c++)
	{
		

		System.out.print(c+ " ");
        
	}
	System.out.println();

	int d='0';
	for(d='0';d<='9';d++)
	{
		
		System.out.print(d+ " ");
		
	}
	System.out.println();

	int num=0;
	for(num=1;num<=10;num++)
	{
		
		System.out.print(num+ " ");
		
	}
	System.out.println();
}
}

